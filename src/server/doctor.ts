import { execFileSync } from 'node:child_process';
import { existsSync, readdirSync, readFileSync, statSync } from 'node:fs';
import { homedir, platform, release } from 'node:os';
import { join } from 'node:path';
import { findChrome, thisMachine } from './chrome-launch';
import type { Config } from './config';

/**
 * Phase 0 discovery. Inspects the running machine for the facts the plan asks for and prints
 * them as Markdown, ready to be saved as docs/environment.md. Read-only: it changes nothing.
 */

interface Proc {
  pid: string;
  cmd: string;
}

function listProcesses(): Proc[] {
  try {
    if (platform() === 'win32') {
      const out = execFileSync(
        'powershell',
        [
          '-NoProfile',
          '-Command',
          // No double quotes inside the command: they do not survive Windows argument quoting reliably.
          "Get-CimInstance Win32_Process | Where-Object { $_.Name -match 'chrome|java|postgres|pg_ctl' } | ForEach-Object { [string]$_.ProcessId + [char]9 + $_.CommandLine }",
        ],
        { encoding: 'utf8', maxBuffer: 32 * 1024 * 1024 },
      );
      return out.split(/\r?\n/).filter(Boolean).map((l) => {
        const i = l.indexOf('\t');
        return { pid: l.slice(0, i), cmd: l.slice(i + 1) };
      });
    }
    const out = execFileSync('ps', ['-A', '-ww', '-o', 'pid=,args='], { encoding: 'utf8', maxBuffer: 32 * 1024 * 1024 });
    return out.split('\n').filter(Boolean).map((l) => {
      const m = /^\s*(\d+)\s+(.*)$/.exec(l);
      return m ? { pid: m[1], cmd: m[2] } : { pid: '', cmd: l };
    });
  } catch {
    return [];
  }
}

/**
 * Reads `--flag=value` or `-Dkey=value` from a command line. Handles the three ways a value with
 * spaces gets quoted: `--flag="a b"`, `--flag='a b'` and, common on Windows, `"--flag=a b"`.
 */
export function flag(cmd: string, name: string): string | null {
  const esc = name.replace(/[.*+?^${}()|[\]\\]/g, '\\$&');
  const whole = new RegExp(`"${esc}=([^"]+)"`).exec(cmd);
  if (whole) return whole[1];
  const m = new RegExp(`${esc}=(?:"([^"]+)"|'([^']+)'|(\\S+))`).exec(cmd);
  return m ? (m[1] ?? m[2] ?? m[3]) : null;
}

async function probeCdp(port: number): Promise<{ browser: string; tabs: { url: string; title: string }[] } | null> {
  try {
    const base = `http://127.0.0.1:${port}`;
    const v = (await (await fetch(`${base}/json/version`, { signal: AbortSignal.timeout(1500) })).json()) as any;
    const list = (await (await fetch(`${base}/json`, { signal: AbortSignal.timeout(1500) })).json()) as any[];
    return {
      browser: v.Browser ?? 'unknown',
      tabs: list.filter((t) => t.type === 'page').map((t) => ({ url: t.url, title: t.title })),
    };
  } catch {
    return null;
  }
}

function findFiles(root: string, test: (name: string) => boolean, depth: number, out: string[] = []): string[] {
  if (depth < 0 || out.length > 50) return out;
  let names: string[];
  try {
    names = readdirSync(root);
  } catch {
    return out;
  }
  for (const name of names) {
    if (name === 'node_modules' || name === '.git' || name === 'target' || name === 'build' || name === 'dist') continue;
    const full = join(root, name);
    let st;
    try {
      st = statSync(full);
    } catch {
      continue;
    }
    if (st.isDirectory()) findFiles(full, test, depth - 1, out);
    else if (test(name)) out.push(full);
  }
  return out;
}

const tick = (ok: boolean) => (ok ? 'yes' : 'no');

export async function runDoctor(cfg: Config, projectDir: string | null): Promise<string> {
  const md: string[] = [];
  const todo: string[] = [];
  const procs = listProcesses();

  md.push('# Environment', '');
  md.push(`Generated by \`debug-hub doctor\` on ${new Date().toISOString()}. Review and correct anything that looks wrong.`, '');

  // 7. Platform
  md.push('## Platform', '');
  md.push(`- OS: ${platform()} ${release()}`);
  md.push(`- Node.js: ${process.version}`, '');

  // 1 + 2. Chrome
  md.push('## Chrome (CDP port and profile)', '');
  const chromeProcs = procs.filter((p) => /chrom(e|ium)/i.test(p.cmd) && !/--type=/.test(p.cmd));
  const ports = new Set<number>([cfg.chrome.port]);
  let usesPipe = false;
  const debuggable = chromeProcs.filter((p) => /--remote-debugging-(port|pipe)/.test(p.cmd));
  if (chromeProcs.length === 0) md.push('- No running Chrome process found. Start the IntelliJ debug session and re-run.');
  else if (debuggable.length === 0) md.push(`- ${chromeProcs.length} Chrome process(es) running, none started with a remote debugging flag.`);
  for (const p of debuggable) {
    const portFlag = flag(p.cmd, '--remote-debugging-port');
    const dataDir = flag(p.cmd, '--user-data-dir');
    if (/--remote-debugging-pipe/.test(p.cmd)) usesPipe = true;
    let port = portFlag ? Number(portFlag) : null;
    if (port === 0 && dataDir) {
      // Port 0 means "pick one"; Chrome writes the choice to this file.
      try {
        port = Number(readFileSync(join(dataDir, 'DevToolsActivePort'), 'utf8').split('\n')[0]);
      } catch {
        port = null;
      }
    }
    if (port) ports.add(port);
    md.push(`- Chrome pid ${p.pid}: debugging port ${port ?? 'not set'}; profile ${dataDir ? `\`${dataDir}\` (dedicated)` : 'default (the everyday profile)'}`);
    if (!dataDir && portFlag) {
      // Chrome 136 and later refuse the debugging port on the default profile, without an error
      // anyone sees: the browser opens normally and the port simply stays closed.
      md.push('  - **Google Chrome 136 and later keep the debugging port closed here**: the port needs a `--user-data-dir` of its own. (Chromium and Chrome for Testing do not enforce this.)');
      todo.push(
        `Chrome pid ${p.pid} was started with \`--remote-debugging-port\` but no \`--user-data-dir\`, so it runs on the everyday profile, where Chrome 136 and later keep the debugging port closed. Close Chrome and use Start Chrome in Debug Hub, or add a dedicated \`--user-data-dir\` to the IntelliJ run configuration.`,
      );
    }
  }
  const where = findChrome(cfg.chrome.executable, thisMachine());
  md.push(`- Chrome program for Start Chrome: ${where.path ? `\`${where.path}\`${where.source === 'settings' ? ' (from settings)' : ''}` : (where.problem ?? 'not found')}`);
  let cdpOk = false;
  for (const port of ports) {
    const r = await probeCdp(port);
    if (!r) {
      md.push(`- \`http://localhost:${port}/json\`: no answer`);
      continue;
    }
    cdpOk = true;
    md.push(`- \`http://localhost:${port}/json\`: **${r.browser}**, ${r.tabs.length} tab(s)`);
    for (const t of r.tabs.slice(0, 8)) md.push(`  - ${t.title || '(untitled)'}: ${t.url}`);
    if (port !== cfg.chrome.port) todo.push(`Set \`chrome.port\` to ${port} in debug-hub.config.json.`);
  }
  if (!cdpOk) {
    todo.push(
      usesPipe
        ? 'Chrome was started with `--remote-debugging-pipe`, which only its parent process can use. Add `--remote-debugging-port=9222` to the browser settings in IntelliJ (Settings > Tools > Web Browsers > Chrome > Edit > Command-line options).'
        : `No CDP endpoint answered. Use Start Chrome in Debug Hub, or add \`--remote-debugging-port=${cfg.chrome.port}\` and a dedicated \`--user-data-dir\` to the Chrome command-line options in IntelliJ, restart the debug session and re-run.`,
    );
  }
  md.push('');

  // 3. Tomcat
  md.push('## Tomcat', '');
  const bases = new Set<string>();
  for (const p of procs) {
    if (!/java/i.test(p.cmd)) continue;
    const base = flag(p.cmd, '-Dcatalina.base');
    if (base) bases.add(base);
  }
  if (bases.size === 0) {
    md.push('- No running Tomcat (`-Dcatalina.base`) found. Start the server from IntelliJ and re-run.');
    todo.push('Find `CATALINA_BASE` (IntelliJ prints it as "Using CATALINA_BASE" at the top of the server console; on Windows it is usually under `%LOCALAPPDATA%\\JetBrains\\<IDE version>\\tomcat\\`).');
  }
  for (const base of bases) {
    md.push(`- \`CATALINA_BASE\`: \`${base}\``);
    const logs = join(base, 'logs');
    let names: string[] = [];
    try {
      names = readdirSync(logs);
    } catch {
      md.push(`  - \`${logs}\` does not exist or is not readable`);
    }
    const has = (re: RegExp) => names.some((n) => re.test(n));
    md.push(`  - \`catalina.out\`: ${tick(has(/^catalina\.out$/))}`);
    md.push(`  - \`catalina.<date>.log\`: ${tick(has(/^catalina\..*\.log$/))}`);
    md.push(`  - \`localhost.<date>.log\`: ${tick(has(/^localhost\..*\.log$/))}`);
    md.push(`  - \`localhost_access_log.<date>.txt\`: ${tick(has(/^localhost_access_log\./))}`);
    if (!has(/^catalina\.out$/)) {
      md.push('  - Note: IntelliJ usually shows stdout in its own console instead of writing `catalina.out`. Application logs must go to a file for the hub to see them.');
    }
    try {
      const xml = readFileSync(join(base, 'conf', 'server.xml'), 'utf8');
      const valve = /<Valve[^>]*AccessLogValve[^>]*>/s.exec(xml)?.[0];
      const pattern = valve ? /pattern="([^"]*)"/.exec(valve)?.[1] : null;
      md.push(`  - Access log valve: ${valve ? `pattern \`${pattern ?? 'default'}\`` : 'not configured'}`);
      if (!valve) todo.push('Enable the AccessLogValve in `conf/server.xml` (see docs/correlation.md for the pattern).');
    } catch {
      md.push('  - `conf/server.xml`: not readable');
    }
    md.push('  - Suggested config:', '    ```json', `    "tomcat": { "enabled": true, "appLogs": ["${logs.replace(/\\/g, '/')}/catalina*", "${logs.replace(/\\/g, '/')}/localhost.*.log"], "accessLogs": ["${logs.replace(/\\/g, '/')}/localhost_access_log.*.txt"] }`, '    ```');
  }
  md.push('');

  // 4 + 5. Project scan
  md.push('## Application project', '');
  if (!projectDir) {
    md.push('- Not scanned. Re-run with `--project <path to the app repo>` to detect the logging framework and Vite proxy.');
    todo.push('Run `debug-hub doctor --project <app repo>`.');
  } else {
    md.push(`- Project: \`${projectDir}\``);
    const builds = findFiles(projectDir, (n) => n === 'pom.xml' || /^build\.gradle(\.kts)?$/.test(n), 3);
    const text = builds.map((f) => readFileSync(f, 'utf8')).join('\n');
    const frameworks = [
      /log4j-core|log4j-slf4j|spring-boot-starter-log4j2/.test(text) && 'Log4j2',
      /logback|spring-boot-starter(?!-log4j2)/.test(text) && 'Logback',
    ].filter(Boolean);
    md.push(`- Build files: ${builds.length ? builds.map((b) => `\`${b}\``).join(', ') : 'none found'}`);
    md.push(`- Logging framework: ${frameworks.length ? frameworks.join(' and ') : builds.length ? 'none declared, so probably JUL (java.util.logging)' : 'unknown'}`);
    const vite = findFiles(projectDir, (n) => /^vite\.config\.(js|ts|mjs|cjs|mts)$/.test(n), 3);
    if (vite.length === 0) md.push('- Vite config: not found');
    for (const v of vite) {
      const src = readFileSync(v, 'utf8');
      const proxy = /proxy\s*:/.test(src);
      const targets = [...src.matchAll(/target\s*:\s*['"`]([^'"`]+)['"`]/g)].map((m) => m[1]);
      md.push(`- Vite config \`${v}\`: ${proxy ? `has \`server.proxy\`${targets.length ? ` → ${targets.join(', ')}` : ''}` : 'no `server.proxy` entry'}`);
      if (!proxy) todo.push('There is no Vite proxy, so request-ID injection has to happen in the app (servlet filter) instead.');
    }
  }
  md.push('');

  // 6. Postgres
  md.push('## Postgres', '');
  const pg = procs.filter((p) => /postgres|postmaster/i.test(p.cmd) && /\s-D[ =]?\S+/.test(p.cmd));
  if (pg.length === 0) md.push('- No running `postgres -D <data dir>` process found.');
  for (const p of pg) {
    const m = /\s-D[ =]?("([^"]+)"|\S+)/.exec(p.cmd);
    const dataDir = m ? (m[2] ?? m[1]) : null;
    if (!dataDir) continue;
    md.push(`- Data directory: \`${dataDir}\``);
    for (const sub of ['log', 'pg_log']) {
      const dir = join(dataDir, sub);
      if (existsSync(dir)) md.push(`  - Log directory candidate: \`${dir}\``);
    }
  }
  md.push('- Run these in `psql` and paste the output here:', '  ```sql', '  SHOW log_destination; SHOW logging_collector; SHOW log_directory; SHOW log_filename;', '  SHOW log_min_duration_statement; SHOW log_line_prefix; SHOW shared_preload_libraries;', "  SELECT name FROM pg_available_extensions WHERE name IN ('pg_stat_statements', 'auto_explain');", '  ```');
  todo.push('Paste the Postgres `SHOW` output into this file.');
  md.push('');

  md.push('## Open items', '');
  for (const t of todo) md.push(`- [ ] ${t}`);
  md.push('- [ ] Owner has reviewed this file.', '');
  md.push(`_Home directory: \`${homedir()}\`. Nothing in this report left the machine._`, '');
  return md.join('\n');
}
